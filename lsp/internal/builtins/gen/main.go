// Command gen turns the vendored `tilt dump api-docs` stub tree into
// internal/builtins/builtins_gen.go.
//
// Usage, from the lsp module root:
//
//	go run ./internal/builtins/gen -in internal/builtins/gen/api -out internal/builtins/builtins_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"text/template"
)

func main() {
	in := flag.String("in", "internal/builtins/gen/api", "stub tree to read")
	out := flag.String("out", "internal/builtins/builtins_gen.go", "Go file to write")
	grammar := flag.String("grammar", "", "TextMate grammar whose builtin lists to rewrite")
	flag.Parse()

	if err := run(*in, *out, *grammar); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func run(in, out, grammar string) error {
	decls, version, err := parseTree(in)
	if err != nil {
		return err
	}
	if len(decls) == 0 {
		return fmt.Errorf("no declarations found in %s", in)
	}
	sort.Slice(decls, func(i, j int) bool {
		a, b := qualified(decls[i]), qualified(decls[j])
		return a < b
	})

	var buf bytes.Buffer
	data := struct {
		Version string
		Decls   []decl
		Count   int
	}{version, decls, len(decls)}
	if err := tmpl.Execute(&buf, data); err != nil {
		return err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("generated code does not compile: %w", err)
	}
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("gen: %d symbols from Tilt %s -> %s\n", len(decls), version, out)

	if grammar != "" {
		if err := writeGrammar(grammar, decls); err != nil {
			return fmt.Errorf("grammar: %w", err)
		}
		fmt.Printf("gen: builtin lists -> %s\n", grammar)
	}
	return nil
}

func qualified(d decl) string {
	if d.Namespace == "" {
		return d.Name
	}
	return d.Namespace + "." + d.Name
}

var tmpl = template.Must(template.New("builtins").Funcs(template.FuncMap{
	"qualified": qualified,
	"kind": func(k string) string {
		switch k {
		case "func":
			return "KindFunc"
		case "class":
			return "KindClass"
		case "var":
			return "KindVar"
		}
		return "KindConst"
	},
}).Parse(`// Code generated by internal/builtins/gen. DO NOT EDIT.
//
// Source: the stub tree written by ` + "`tilt dump api-docs`" + `.
// Regenerate with: make lsp-dump && make lsp-gen

package builtins

// TiltVersion is the Tilt release the table describes.
const TiltVersion = "{{ .Version }}"

// Symbols is keyed by qualified name: "local_resource", "os.path.abspath".
var Symbols = map[string]Symbol{
{{- range .Decls }}
	{{ printf "%q" (qualified .) }}: {
		Name:      {{ printf "%q" .Name }},
		Namespace: {{ printf "%q" .Namespace }},
		Kind:      {{ kind .Kind }},
		{{- if .Returns }}
		Returns:   {{ printf "%q" .Returns }},
		{{- end }}
		{{- if .Type }}
		Type:      {{ printf "%q" .Type }},
		{{- end }}
		{{- if .Doc }}
		Doc:       {{ printf "%q" .Doc }},
		{{- end }}
		{{- if .Params }}
		Params: []Param{
			{{- range .Params }}
			{Name: {{ printf "%q" .Name }}{{ if .Type }}, Type: {{ printf "%q" .Type }}{{ end }}{{ if .Default }}, Default: {{ printf "%q" .Default }}{{ end }}{{ if .Doc }}, Doc: {{ printf "%q" .Doc }}{{ end }}},
			{{- end }}
		},
		{{- end }}
	},
{{- end }}
}
`))
