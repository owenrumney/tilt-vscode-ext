package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// decl is one parsed stub declaration, before it becomes a Symbol.
type decl struct {
	Name      string
	Namespace string
	Kind      string // "func" | "class" | "var" | "const"
	Params    []param
	Returns   string
	Doc       string
	Type      string
}

type param struct {
	Name    string
	Type    string
	Default string
	Doc     string
}

var (
	defRe   = regexp.MustCompile(`^def ([A-Za-z_][A-Za-z0-9_]*)\(`)
	classRe = regexp.MustCompile(`^class ([A-Za-z_][A-Za-z0-9_]*)\s*[:(]`)
	varRe   = regexp.MustCompile(`^([a-z_][A-Za-z0-9_]*)\s*:\s*([^=]+?)\s*=`)
	constRe = regexp.MustCompile(`^([A-Z][A-Z0-9_]*)\s*=`)
	// An unannotated module member, documented by the docstring below it:
	//   environ = Dict[str, str]
	//   """A dictionary of your environment variables."""
	bareRe = regexp.MustCompile(`^([a-z_][A-Za-z0-9_]*)\s*=\s*(.+)$`)
	// A Tilt version stamp, present in every generated stub.
	versionRe = regexp.MustCompile(`Generated by Tilt version (v[0-9][^,]*)`)
)

// parseTree reads every .py file under root and returns the declarations plus
// the Tilt version the stubs were generated from.
func parseTree(root string) ([]decl, string, error) {
	var decls []decl
	version := ""

	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || filepath.Ext(path) != ".py" {
			return err
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if m := versionRe.FindSubmatch(src); m != nil && version == "" {
			version = string(m[1])
		}
		ns, err := namespaceOf(root, path)
		if err != nil {
			return err
		}
		decls = append(decls, parseFile(string(src), ns)...)
		return nil
	})
	if err != nil {
		return nil, "", err
	}
	if version == "" {
		return nil, "", fmt.Errorf("no Tilt version stamp found under %s", root)
	}
	return decls, version, nil
}

// namespaceOf turns api/os/path.py into "os.path" and api/__init__.py into "".
func namespaceOf(root, path string) (string, error) {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return "", err
	}
	dir, file := filepath.Split(rel)
	parts := strings.Split(strings.Trim(filepath.ToSlash(dir), "/"), "/")
	// The first element is the package directory itself ("api"), not a namespace.
	if len(parts) > 0 && (parts[0] == "api" || parts[0] == ".") {
		parts = parts[1:]
	}
	if file != "__init__.py" {
		parts = append(parts, strings.TrimSuffix(file, ".py"))
	}
	var kept []string
	for _, p := range parts {
		if p != "" {
			kept = append(kept, p)
		}
	}
	return strings.Join(kept, "."), nil
}

func parseFile(src, namespace string) []decl {
	lines := strings.Split(src, "\n")
	var out []decl

	for i := 0; i < len(lines); i++ {
		line := lines[i]
		switch {
		case defRe.MatchString(line):
			d, next := parseDef(lines, i, namespace)
			out = append(out, d)
			i = next
		case classRe.MatchString(line):
			name := classRe.FindStringSubmatch(line)[1]
			doc, next := docstringAfter(lines, i+1)
			prose, _ := splitDocstring(doc)
			out = append(out, decl{
				Name: name, Namespace: namespace, Kind: "class", Doc: prose,
			})
			i = next
		case constRe.MatchString(line):
			// The right-hand side may be a multi-line type() call; its value is
			// never useful, so only the name is kept.
			name := constRe.FindStringSubmatch(line)[1]
			out = append(out, decl{
				Name: name, Namespace: namespace, Kind: "const",
				Doc: toMarkdown(commentAbove(lines, i)),
			})
		case bareRe.MatchString(line) && !varRe.MatchString(line):
			m := bareRe.FindStringSubmatch(line)
			// A docstring is what marks an assignment as API rather than
			// internal plumbing, so one is required here.
			doc, next := docstringAfter(lines, i+1)
			if strings.TrimSpace(doc) == "" {
				continue
			}
			prose, _ := splitDocstring(doc)
			out = append(out, decl{
				Name: m[1], Namespace: namespace, Kind: "var",
				Type: strings.TrimSpace(m[2]), Doc: prose,
			})
			i = next
		case varRe.MatchString(line):
			m := varRe.FindStringSubmatch(line)
			if strings.HasPrefix(m[1], "__") || m[1] == "file__" {
				continue
			}
			doc, next := docstringAfter(lines, i+1)
			prose, _ := splitDocstring(doc)
			out = append(out, decl{
				Name: m[1], Namespace: namespace, Kind: "var",
				Type: strings.TrimSpace(m[2]), Doc: prose,
			})
			i = next
		}
	}
	return out
}

// parseDef collects a def's signature, which may wrap over many lines, then
// its docstring. It returns the index of the last line consumed.
func parseDef(lines []string, start int, namespace string) (decl, int) {
	name := defRe.FindStringSubmatch(lines[start])[1]

	// Gather from the first "(" until parens balance.
	var sb strings.Builder
	depth := 0
	i := start
	opened := false
	for ; i < len(lines); i++ {
		for _, r := range lines[i] {
			switch r {
			case '(', '[', '{':
				depth++
				opened = true
			case ')', ']', '}':
				depth--
			}
			sb.WriteRune(r)
		}
		if opened && depth <= 0 {
			break
		}
		sb.WriteRune(' ')
	}
	text := sb.String()

	open := strings.Index(text, "(")
	closeAt := strings.LastIndex(text, ")")
	params := []param{}
	if open >= 0 && closeAt > open {
		params = parseParams(text[open+1 : closeAt])
	}
	returns := ""
	if arrow := strings.Index(text[min(closeAt+1, len(text)):], "->"); arrow >= 0 {
		rest := text[closeAt+1+arrow+2:]
		returns = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(rest), ":"))
	}

	doc, next := docstringAfter(lines, i+1)
	summary, argDocs := splitDocstring(doc)
	for j := range params {
		if d, ok := argDocs[params[j].Name]; ok {
			params[j].Doc = d
		}
	}
	return decl{
		Name: name, Namespace: namespace, Kind: "func",
		Params: params, Returns: returns, Doc: summary,
	}, next
}

// parseParams splits a signature body on commas at depth zero, so that
// Union[str, List[str]] and {} defaults survive.
func parseParams(body string) []param {
	var out []param
	depth := 0
	cur := strings.Builder{}
	flush := func() {
		text := strings.TrimSpace(cur.String())
		cur.Reset()
		if text == "" || text == "*" || strings.HasPrefix(text, "*") {
			return
		}
		out = append(out, parseParam(text))
	}
	inStr := byte(0)
	for i := 0; i < len(body); i++ {
		c := body[i]
		switch {
		case inStr != 0:
			if c == inStr {
				inStr = 0
			}
		case c == '\'' || c == '"':
			inStr = c
		case c == '(' || c == '[' || c == '{':
			depth++
		case c == ')' || c == ']' || c == '}':
			depth--
		case c == ',' && depth == 0:
			flush()
			continue
		}
		cur.WriteByte(c)
	}
	flush()
	return out
}

// parseParam reads "name: Type = default" with either half optional.
func parseParam(text string) param {
	p := param{}
	rest := text

	// The default is after the first "=" at depth zero.
	if i := splitAt(rest, '='); i >= 0 {
		p.Default = strings.TrimSpace(rest[i+1:])
		rest = strings.TrimSpace(rest[:i])
	}
	if i := splitAt(rest, ':'); i >= 0 {
		p.Type = strings.TrimSpace(rest[i+1:])
		rest = strings.TrimSpace(rest[:i])
	}
	p.Name = strings.TrimSpace(rest)
	return p
}

// splitAt finds the first occurrence of sep outside brackets and strings.
func splitAt(s string, sep byte) int {
	depth := 0
	inStr := byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case inStr != 0:
			if c == inStr {
				inStr = 0
			}
		case c == '\'' || c == '"':
			inStr = c
		case c == '(' || c == '[' || c == '{':
			depth++
		case c == ')' || c == ']' || c == '}':
			depth--
		case c == sep && depth == 0:
			return i
		}
	}
	return -1
}

// docstringAfter reads a triple-quoted string starting at or after `from`,
// skipping blank lines. It returns the raw text and the last line consumed.
func docstringAfter(lines []string, from int) (string, int) {
	i := from
	for i < len(lines) && strings.TrimSpace(lines[i]) == "" {
		i++
	}
	if i >= len(lines) {
		return "", len(lines) - 1
	}
	trimmed := strings.TrimSpace(lines[i])
	quote := ""
	for _, q := range []string{`"""`, `'''`} {
		if strings.HasPrefix(trimmed, q) {
			quote = q
		}
	}
	if quote == "" {
		return "", from - 1
	}

	body := strings.TrimPrefix(trimmed, quote)
	if strings.HasSuffix(body, quote) && len(body) >= len(quote) {
		return strings.TrimSuffix(body, quote), i
	}
	var sb strings.Builder
	sb.WriteString(body)
	for i++; i < len(lines); i++ {
		if idx := strings.Index(lines[i], quote); idx >= 0 {
			sb.WriteString("\n" + lines[i][:idx])
			return sb.String(), i
		}
		sb.WriteString("\n" + lines[i])
	}
	return sb.String(), len(lines) - 1
}

// commentAbove collects the "#" comment block immediately above a line.
func commentAbove(lines []string, at int) string {
	var collected []string
	for i := at - 1; i >= 0; i-- {
		t := strings.TrimSpace(lines[i])
		if !strings.HasPrefix(t, "#") || strings.HasPrefix(t, "###") {
			break
		}
		collected = append([]string{strings.TrimSpace(strings.TrimPrefix(t, "#"))}, collected...)
	}
	return strings.Join(collected, " ")
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
